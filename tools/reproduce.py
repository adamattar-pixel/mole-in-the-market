"""R15: recompute every table from runs/ with no API key and no network, with checksums.

Usage:
  python -m tools.reproduce runs results --viz-dir viz/data --figures-dir figures

Outputs in the out dir: labels.csv (R14), summary.json, tables.md, detectors.json and detectors.md (R30,
exploratory detector scores of R29 on the same kept games), checksums.txt.
With --viz-dir: the viz export (R22, checked by R23). With --figures-dir: figures/game_grid.pdf (R27).

The CLI keeps only real games (log field mock false) from the preregistered configs (PREREG_CONFIGS, read
from the game id prefix "<config name>__"). Excluded games are counted in summary.json and tables.md.
--all-configs and --include-mock bring them back for diagnostics only (never for the report tables).
"""
import argparse
import hashlib
import json
import subprocess
from collections import Counter
from pathlib import Path

from harness.conditions import CONDITIONS, PREREG_PATH, load_prereg_texts
from harness.labels import family_base_rates, make_labels, write_labels_csv
from harness.metrics import (behavioral_acceptance_game, false_positive_rate, game_rate, permutation_p_value,
                             verbal_acceptance_game, wilson)
from harness.runlog import load_logs
from harness.validation import e_validation
from harness.vizexport import CONDITION_NAMES, check_consistency, export_viz, make_game_grid
from tools.score_detectors import score_detectors, write_outputs as write_detector_outputs


PREREG_CONFIGS = ("espion_pilot", "espion_core")  # A and E from the pilot, B, B_T, C, D from the core


def config_name(log):
    return str(log["game_id"]).split("__", 1)[0]


def filter_logs(logs, configs=None, include_mock=True):
    """(kept, excluded). configs None = every config. A log without mock false counts as mock."""
    kept, excluded = [], {"mock": 0, "non_core_config": {}}
    for g in logs:
        if not include_mock and g.get("mock") is not False:
            excluded["mock"] += 1
        elif configs is not None and config_name(g) not in configs:
            name = config_name(g)
            excluded["non_core_config"][name] = excluded["non_core_config"].get(name, 0) + 1
        else:
            kept.append(g)
    return kept, excluded


def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _rate(k, n):
    return {"k": k, "n": n, "rate": (k / n) if n else None, "ci": list(wilson(k, n)) if n else None}


def _generated_at():
    """Commit date of HEAD: stable across runs at the same commit (no wall clock, so output is deterministic)."""
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cI"], cwd=Path(__file__).resolve().parent.parent,
                             capture_output=True, text=True, check=True)
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def build_summary(logs, texts, n_draws, seed):
    base = family_base_rates(logs, n_draws, seed)
    summary = {"n_games": len(logs), "n_draws": n_draws, "seed": seed, "rates": {}, "false_positives": {},
               "base_rate": {}, "say_do_2x2": {},
               "e_validation": e_validation(logs, texts["e_threshold_gap_fraction"])}
    for fam in sorted({g["family"] for g in logs}):
        fl = [g for g in logs if g["family"] == fam]
        draws = base[fam]
        summary["base_rate"][fam] = None if draws is None else {
            "mean": sum(draws) / len(draws), "min": min(draws), "max": max(draws)}
        summary["rates"][fam], summary["say_do_2x2"][fam] = {}, {}
        for c in CONDITIONS:
            cl = [g for g in fl if g["condition"] == c]
            if not cl:
                continue
            say, do = game_rate(cl, verbal_acceptance_game), game_rate(cl, behavioral_acceptance_game)
            entry = {"n": len(cl), "say": _rate(*say), "do": _rate(*do)}
            entry["do"]["p_value_vs_base_rate"] = None if draws is None else permutation_p_value(do[0] / do[1], draws)
            summary["rates"][fam][c] = entry
            cells = {"say1_do1": 0, "say1_do0": 0, "say0_do1": 0, "say0_do0": 0}
            for g in cl:
                cells[f"say{int(verbal_acceptance_game(g))}_do{int(behavioral_acceptance_game(g))}"] += 1
            summary["say_do_2x2"][fam][c] = cells
        k, n = false_positive_rate(fl)
        if n:
            summary["false_positives"][fam] = _rate(k, n)
    return summary, base


def _fmt_rate(r):
    if r["n"] == 0:
        return "-"
    lo, hi = r["ci"]
    return f"{r['k']}/{r['n']} ({r['rate']:.2f}, 95% CI {lo:.2f}-{hi:.2f})"


def tables_md(summary):
    lines = ["# Tables (generated by tools/reproduce.py, do not edit)", "", f"Games: {summary['n_games']}"]
    ex = summary.get("excluded")
    if ex is not None:
        parts = [f"mock {ex['mock']}"] + [f"non-core config {k} {v}" for k, v in
                                          sorted(ex["non_core_config"].items())]
        n_ex = ex["mock"] + sum(ex["non_core_config"].values())
        lines.append(f"Excluded games: {n_ex} ({', '.join(parts)})")
    lines.append("")
    if not summary["n_games"]:
        lines.append("No games in runs/.")
    for fam, rates in summary["rates"].items():
        lines += [f"## Family {fam}", "", "| Condition | Games | Say | Do | Do p-value vs base rate |",
                  "|---|---|---|---|---|"]
        for c, e in rates.items():
            p = e["do"]["p_value_vs_base_rate"]
            lines.append(f"| {CONDITION_NAMES[c]} | {e['n']} | {_fmt_rate(e['say'])} | {_fmt_rate(e['do'])} | "
                         f"{'-' if p is None else f'{p:.3f}'} |")
        br = summary["base_rate"][fam]
        lines.append("")
        br_text = "not available" if br is None else f"mean {br['mean']:.3f}"
        lines.append(f"Base rate (A and D, permutation): {br_text}")
        fp = summary["false_positives"].get(fam)
        lines.append(f"False positives (accept in D): {'no D games' if fp is None else _fmt_rate(fp)}")
        ev = summary["e_validation"][fam]
        eff = "n/a" if ev["effect_gap_fraction"] is None else f"{ev['effect_gap_fraction']:.3f}"
        lines.append(f"Positive control E: {'PASS' if ev['pass'] else 'FAIL'} (effect {eff} of the gap, threshold {ev['threshold']})")
        lines.append("")
    return "\n".join(lines) + "\n"


def reproduce(runs_dir, out_dir, n_draws=1000, seed=0, viz_dir=None, figures_dir=None, prereg_path=None,
              configs=None, include_mock=True):
    runs_dir, out_dir = Path(runs_dir), Path(out_dir)
    prereg_path = Path(prereg_path or PREREG_PATH)
    out_dir.mkdir(parents=True, exist_ok=True)
    logs = load_logs(runs_dir)
    if len({bool(g.get("memory", False)) for g in logs}) > 1:
        raise ValueError("runs dir mixes exploratory memory logs with frozen logs: reproduce each folder separately")
    logs, excluded = filter_logs(logs, configs, include_mock)
    texts = load_prereg_texts(prereg_path)
    summary, base = build_summary(logs, texts, n_draws, seed)
    summary["excluded"] = excluded
    summary["included_configs"] = dict(sorted(Counter(map(config_name, logs)).items()))
    rows = make_labels(logs, n_draws=n_draws, seed=seed, base_rates=base)
    write_labels_csv(rows, out_dir / "labels.csv")
    (out_dir / "summary.json").write_text(json.dumps(summary, sort_keys=True, indent=1) + "\n", encoding="utf-8")
    (out_dir / "tables.md").write_text(tables_md(summary), encoding="utf-8")
    write_detector_outputs(score_detectors(logs, n_draws=n_draws, seed=seed), out_dir)

    input_lines = sorted(f"{_sha(p)}  runs/{p.name}" for p in runs_dir.glob("*.json"))
    output_lines = [f"{_sha(out_dir / n)}  out/{n}" for n in ("labels.csv", "summary.json", "tables.md",
                                                               "detectors.json", "detectors.md")]
    (out_dir / "checksums.txt").write_text("\n".join(input_lines + output_lines) + "\n", encoding="utf-8")

    if viz_dir is not None:
        source = hashlib.sha256("\n".join(input_lines).encode("utf-8")).hexdigest()
        export_viz(logs, rows, viz_dir, texts, prereg_path, source, _generated_at())
        n_excluded = excluded["mock"] + sum(excluded["non_core_config"].values())
        problems = check_consistency(out_dir / "labels.csv", Path(viz_dir) / "games.csv", runs_dir, n_excluded)
        if problems:
            raise RuntimeError("viz export inconsistent with labels.csv: " + "; ".join(problems))
    if figures_dir is not None:
        if viz_dir is None:
            raise ValueError("figures need the viz export (games.csv): pass viz_dir")
        make_game_grid(Path(viz_dir) / "games.csv", Path(figures_dir) / "game_grid.pdf")
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs_dir", nargs="?", default="runs")
    ap.add_argument("out_dir", nargs="?", default="results")
    ap.add_argument("--viz-dir", default=None)
    ap.add_argument("--figures-dir", default=None)
    ap.add_argument("--n-draws", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--configs", default=",".join(PREREG_CONFIGS),
                    help="comma-separated config names to keep (default: the preregistered configs)")
    ap.add_argument("--all-configs", action="store_true", help="diagnostics: keep every config (smoke too)")
    ap.add_argument("--include-mock", action="store_true", help="diagnostics: keep mock (dry run) games")
    a = ap.parse_args(argv)
    configs = None if a.all_configs else tuple(c.strip() for c in a.configs.split(",") if c.strip())
    s = reproduce(a.runs_dir, a.out_dir, n_draws=a.n_draws, seed=a.seed, viz_dir=a.viz_dir,
                  figures_dir=a.figures_dir, configs=configs, include_mock=a.include_mock)
    ex = s["excluded"]
    print(f"reproduce: {s['n_games']} games -> {a.out_dir} (excluded: mock {ex['mock']}, "
          f"non-core config {sum(ex['non_core_config'].values())})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
