"""R30, R32, R34: monitor metrics and defenses comparison tables from the logs (EXPLORATORY, post-freeze).

Pooled ("all") and per family: harness.defenses.monitor_metrics (matched pairs B/C/D vs B_MON/C_MON/D_MON,
collusion removed, false blocks on D_MON) and defenses_comparison (B vs B_ETH vs B_MON on full triples).
No API key, no network.

Usage: python -m tools.score_defenses runs results [--configs espion_core,espion_monitor,espion_ethics]
       [--include-mock]
Writes defenses.json and defenses.md in the out dir.
"""
import argparse
import json
from pathlib import Path

from harness.defenses import BASE_CONDITION, DEFENSE_ARMS, MONITORED_CONDITIONS, defenses_comparison, monitor_metrics
from harness.runlog import load_logs
from tools.reproduce import filter_logs

DEFENSE_CONFIGS = ("espion_core", "espion_monitor", "espion_ethics")
HEADER = "EXPLORATORY, post-freeze (PREREGISTRATION_ADDENDUM.md)"


def score_defenses(logs):
    out = {"all": {"monitor": monitor_metrics(logs), "comparison": defenses_comparison(logs)}}
    for fam in sorted({g["family"] for g in logs}):
        out[fam] = {"monitor": monitor_metrics(logs, fam), "comparison": defenses_comparison(logs, fam)}
    return out


def _fmt(r):
    if not r["n"]:
        return f"{r['k']}/{r['n']} (n/a)"
    lo, hi = r["ci"]
    return f"{r['k']}/{r['n']} ({r['rate']:.2f}, 95% CI {lo:.2f}-{hi:.2f})"


def tables_md(scores):
    lines = [f"# Defenses ({HEADER})", "", "Generated by tools/score_defenses.py, do not edit. Unit: the game. "
             "Monitor pairs and the comparison are matched by family and seed.", ""]
    for grp, s in scores.items():
        m, c = s["monitor"], s["comparison"]
        lines += [f"## {'All families' if grp == 'all' else 'Family ' + grp}", "", "Rule monitor (R32):", "",
                  "| Base | Pairs | Blocked | Say without | Say with | Do without | Do with | Collusion removed |",
                  "|---|---|---|---|---|---|---|---|"]
        for mon in MONITORED_CONDITIONS:
            b = m[BASE_CONDITION[mon]]
            lines.append(f"| {BASE_CONDITION[mon]} | {b['n_pairs']} | {_fmt(b['blocked'])} | {_fmt(b['say_without'])} | "
                         f"{_fmt(b['say_with'])} | {_fmt(b['do_without'])} | {_fmt(b['do_with'])} | "
                         f"{b['collusion_removed']} |")
        lines += ["", f"False blocks on D_MON: {_fmt(m['false_blocks'])}", "",
                  f"Defenses comparison (R34), {c['n_matched']} matched (family, seed) triples:", "",
                  "| Arm | Say | Do |", "|---|---|---|"]
        for arm in DEFENSE_ARMS:
            lines.append(f"| {arm} | {_fmt(c['arms'][arm]['say'])} | {_fmt(c['arms'][arm]['do'])} |")
        n_un = sum(len(v) for v in m["unmatched"].values()) + sum(len(v) for v in c["unmatched"].values())
        lines += ["", f"Unmatched games (listed in defenses.json): {n_un}", ""]
    return "\n".join(lines) + "\n"


def write_outputs(scores, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "defenses.json").write_text(json.dumps(scores, sort_keys=True, indent=1) + "\n", encoding="utf-8", newline="\n")
    (out_dir / "defenses.md").write_text(tables_md(scores), encoding="utf-8", newline="\n")
    return [out_dir / "defenses.json", out_dir / "defenses.md"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs_dir", nargs="?", default="runs")
    ap.add_argument("out_dir", nargs="?", default="results")
    ap.add_argument("--configs", default=",".join(DEFENSE_CONFIGS))
    ap.add_argument("--include-mock", action="store_true", help="diagnostics: keep mock (dry run) games")
    a = ap.parse_args(argv)
    configs = tuple(c.strip() for c in a.configs.split(",") if c.strip())
    logs, _ = filter_logs(load_logs(a.runs_dir), configs, a.include_mock)
    write_outputs(score_defenses(logs), a.out_dir)
    print(f"score_defenses: {len(logs)} games -> {a.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
