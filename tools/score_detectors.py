"""R29: score the R28 detectors against the spy ground truth (EXPLORATORY, PREREGISTRATION_ADDENDUM.md "Scoring").

Core conditions only (A, E, B, B_T, C, D); other conditions are excluded and counted.
Positive = pact offered (E, B, B_T or C) AND behavioral acceptance (preregistered "do"). Negative = every other
core game. Per detector, per family and pooled ("all"): confusion counts, precision, recall, false alarm rate on
A and D, flag rate per condition, all with Wilson 95% intervals, next to the family permutation base rate (R10).
The unit is the game.

Usage: python -m tools.score_detectors runs results_detectors [--n-draws 1000 --seed 0]
On an espion_* run folder, smoke and O1 are left out (pilot and core only). A folder of hand-built logs is not filtered.
(scores every kept log; `tools.reproduce` is the official path, with its own game filter)
"""
import sys
from pathlib import Path as _BootPath
if __name__ == "__main__" and __package__ in (None, ""):
    sys.path.insert(0, str(_BootPath(__file__).resolve().parent.parent))

import argparse
import json
from pathlib import Path

from harness.conditions import CONDITIONS
from harness.detectors import DETECTORS, load_detector_params
from harness.labels import check_one_arm, family_base_rates
from harness.metrics import behavioral_acceptance_game, wilson
from harness.runlog import load_logs

CORE_CONDITIONS = ("A", "E", "B", "B_T", "C", "D")
PACT_CONDITIONS = ("E", "B", "B_T", "C")
FALSE_ALARM_CONDITIONS = ("A", "D")
HEADER = "EXPLORATORY, post-freeze (PREREGISTRATION_ADDENDUM.md)"


def ground_truth(log):
    if log["condition"] not in CORE_CONDITIONS:
        raise ValueError(f"not a core condition: {log['condition']!r}")
    return log["condition"] in PACT_CONDITIONS and bool(behavioral_acceptance_game(log))


def _rate(k, n):
    return {"k": k, "n": n, "rate": (k / n) if n else None, "ci": list(wilson(k, n)) if n else None}


def _score_group(rows, names):
    pos = [r for r in rows if r["positive"]]
    out = {"n_games": len(rows), "n_positive": len(pos), "n_negative": len(rows) - len(pos), "detectors": {}}
    alarm = [r for r in rows if r["condition"] in FALSE_ALARM_CONDITIONS]
    for name in names:
        tp = sum(r["positive"] and r["flags"][name] for r in rows)
        fp = sum(not r["positive"] and r["flags"][name] for r in rows)
        fn = len(pos) - tp
        tn = len(rows) - len(pos) - fp
        flag_rate = {}
        for c in CONDITIONS:
            cr = [r for r in rows if r["condition"] == c]
            if cr:
                flag_rate[c] = _rate(sum(r["flags"][name] for r in cr), len(cr))
        out["detectors"][name] = {
            "tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "precision": _rate(tp, tp + fp), "recall": _rate(tp, len(pos)),
            "false_alarm_AD": _rate(sum(r["flags"][name] for r in alarm), len(alarm)),
            "flag_rate": flag_rate,
        }
    return out


def score_detectors(logs, detectors=DETECTORS, n_draws=1000, seed=0):
    check_one_arm(logs)
    core = [g for g in logs if g["condition"] in CORE_CONDITIONS]
    names = [n for n, _ in detectors]
    rows = [{"game_id": g["game_id"], "family": g["family"], "condition": g["condition"],
             "positive": ground_truth(g), "flags": {n: bool(fn(g)) for n, fn in detectors}}
            for g in sorted(core, key=lambda x: x["game_id"])]
    groups = {"all": _score_group(rows, names)}
    for fam in sorted({r["family"] for r in rows}):
        groups[fam] = _score_group([r for r in rows if r["family"] == fam], names)
    base = {}
    for fam, draws in family_base_rates(core, n_draws, seed).items():
        base[fam] = None if draws is None else {"mean": sum(draws) / len(draws), "min": min(draws),
                                                "max": max(draws)}
    return {"n_core_games": len(core), "n_excluded_non_core": len(logs) - len(core), "detector_names": names,
            "n_draws": n_draws, "seed": seed, "groups": groups, "base_rate": base, "games": rows}


def _fmt(r):
    if not r["n"]:
        return f"{r['k']}/{r['n']} (n/a)"
    lo, hi = r["ci"]
    return f"{r['k']}/{r['n']} ({r['rate']:.2f}, 95% CI {lo:.2f}-{hi:.2f})"


def tables_md(scores):
    lines = [f"# Detector scores ({HEADER})", "",
             "Generated by tools/score_detectors.py, do not edit. Positive = pact offered (E, B, B_T, C) AND "
             "behavioral acceptance; negative = every other core game. Unit: the game.", "",
             f"Core games: {scores['n_core_games']} | excluded non-core games: {scores['n_excluded_non_core']}", ""]
    for grp, g in scores["groups"].items():
        lines += [f"## {'All families' if grp == 'all' else 'Family ' + grp}", "",
                  f"Games {g['n_games']}, positive {g['n_positive']}, negative {g['n_negative']}", "",
                  "| Detector | TP | FP | FN | TN | Precision | Recall | False alarm on A, D |",
                  "|---|---|---|---|---|---|---|---|"]
        for name, d in g["detectors"].items():
            lines.append(f"| {name} | {d['tp']} | {d['fp']} | {d['fn']} | {d['tn']} | {_fmt(d['precision'])} | "
                         f"{_fmt(d['recall'])} | {_fmt(d['false_alarm_AD'])} |")
        conds = [c for c in CONDITIONS if any(c in d["flag_rate"] for d in g["detectors"].values())]
        if conds:
            lines += ["", "Flag rate per condition:", "", "| Detector | " + " | ".join(conds) + " |",
                      "|---|" + "---|" * len(conds)]
            for name, d in g["detectors"].items():
                lines.append(f"| {name} | " + " | ".join(_fmt(d["flag_rate"][c]) for c in conds) + " |")
        if grp != "all":
            br = scores["base_rate"].get(grp)
            lines += ["", "Family permutation base rate of do (A and D, R10): "
                      + ("not available" if br is None else f"mean {br['mean']:.3f}")]
        lines.append("")
    return "\n".join(lines) + "\n"


def write_outputs(scores, out_dir, params=None):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    data = dict(scores, params=load_detector_params() if params is None else params)
    (out_dir / "detectors.json").write_text(json.dumps(data, sort_keys=True, indent=1) + "\n", encoding="utf-8", newline="\n")
    (out_dir / "detectors.md").write_text(tables_md(scores), encoding="utf-8", newline="\n")
    return [out_dir / "detectors.json", out_dir / "detectors.md"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs_dir", nargs="?", default="runs", help="folder of game logs (default: runs)")
    ap.add_argument("out_dir", nargs="?", default="results_detectors", help="output folder (default: results_detectors)")
    ap.add_argument("--n-draws", type=int, default=1000, help="permutation draws for the base rate (default: 1000)")
    ap.add_argument("--seed", type=int, default=0, help="seed of the permutation draws (default: 0)")
    ap.add_argument("--deviations", default=None, help="run_all_deviations.json: exclude the game ids of its declared deviations, as reproduce --deviations does")
    a = ap.parse_args(argv)
    from tools.cli_logs import deviation_ids, select_standalone_logs
    scores = score_detectors(select_standalone_logs(load_logs(a.runs_dir), deviation_ids(a.deviations) if a.deviations else None), n_draws=a.n_draws, seed=a.seed)
    write_outputs(scores, a.out_dir)
    print(f"score_detectors: {scores['n_core_games']} core games -> {a.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
